 */
class Scripts extends Megad
{


    public static function playSound($sound)
    {
        parent::playSound($sound); // TODO: Change the autogenerated stub
    }




    function set($num, $val, $id_device=null)
    {
        parent::set($num, $val, $id_device); // TODO: Change the autogenerated stub
    }




    /** 
     * Ищем и выполняем скрипты, которые сответсвуют объектам и их методам,
     * подходящим по текущему периоду времени 
    */

    function cron(int $time)
    {
        $this->scheduler('',$time,'c');
    }




    /**
     * Ищем и выполняем скрипты или методы обекта методам из таблицы расписаний
     *
     * @param string $day - день недели, месяца или дата выполнния скрипта
     * @param string $time - время выполнения скрипта
     * @param string $type - тип, по которому отбираем данные d - ежедневные, w - еженедельные, m - ежемесячные, c - ежеминутные
     * @return void
     */

    function scheduler($day, $time, $type)
    {


        $sql = parent::$db->query("SELECT  scheduler_tasks.id AS id_task, scheduler_tasks.method AS method, 
                                          scheduler_tasks.script AS script, scheduler_tasks.object AS id_object 
                                    FROM scheduler_tasks        
                                    INNER JOIN scheduler_points ON scheduler_tasks.id =  scheduler_points.id_task
                                    WHERE scheduler_points.days LIKE '%$day%' AND scheduler_points.time = '$time'
                                    AND `scheduler_points`.`type` = '$type' AND scheduler_tasks.`active` = 1 ");

        while ($action = $sql->fetch(PDO::FETCH_OBJ))
        {
            //Выполняем действие для метода, если он указан. Если не указан, то для скрипта
            if($action->method)
            {
                echo "Run method";
                Action::runAction($action->method, 'scheduler', $action->id_object );
            }
            else
            {
                $this->runscript($action->script);
            }
        }

    }





    /**
     * Выполняем нужный скрипт
     *
     * @param int $id_script ид скрипта
     * @param int $param параметры выполнения скрипта
     */
    function runscript($idScript, $param = null)
    {


        if($idScript) {

            $scriptsql = parent::$db->query("SELECT scripts.link AS link, system, enable FROM scripts 
                                         WHERE scripts.id = $idScript");

            $script = $scriptsql->fetch(PDO::FETCH_OBJ);


            $dir = str_replace(' ', '\ ', __DIR__);

            if($script->system)
                $folder = '../scripts';
            else
                $folder = '../userscripts';

            if($script->enable) {
                 passthru("(cd {$dir} && cd {$folder} && php -f {$script->link} {$param} &) >> /dev/null 2>&1");
                 System::addLog('system', 'Script "' . $script->link . ' ' . $param . '" is running', 'scripts');
            }

            return true;
        }else {
            System::addLog('error', 'Вызван метод, у которого не указан скрипт', 'scripts');
            return false;
        }
        
    }


    /**
     * Функция включения скриптов
     * @param string $idsScripts строка id скриптов через запятую
     */
    function enable($idsScripts) {

        $this->setState($idsScripts, 1);
    }

    /**
     * Функция выключения скриптов
     * @param string $idsScripts строка id скриптов через запятую
     */
    function disable($idsScripts) {

        $this->setState($idsScripts, 0);
    }

    private function setState($idsScripts, $state) {

        $scriptsArray = explode(',',$idsScripts);

        foreach ($scriptsArray as $script) {
            parent::$db->query("UPDATE `scripts` SET `enable` = $state WHERE id= $script AND `system` = 0");
        }
    }


    /**
     * Получение состояние скрипта, включен или выключен
     *
     * @param $idScript
     * @return mixed
     */
    public function getState($idScript) {

        $scriptsql = parent::$db->query("SELECT enable FROM scripts 
                                         WHERE scripts.id = $idScript");

        $state = $scriptsql->fetch(PDO::FETCH_OBJ);

        return $state->enable;
    }




}